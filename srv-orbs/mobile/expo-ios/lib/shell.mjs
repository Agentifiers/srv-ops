// Stages `shell` and `compile`: the app target as a SwiftPM package (what the
// injected .xcodeproj app target is in Xcode), built with SwiftBuild for arm64 iOS.
import fs from 'node:fs';
import path from 'node:path';
import { generatedPaths } from './graph.mjs';
import { requireSdk, swiftTargetArgs } from './context.mjs';
import { exists, fail, info, mkdirp, readJSON, resolvePackageDir, rmrf, run, writeIfChanged } from './util.mjs';

/**
 * Every flavored runtime framework of this configuration (React, ReactNativeDependencies,
 * hermesvm, precompiled Expo modules and their SwiftPM deps), resolved to the iphoneos
 * slice: [{ id, name, executable, dir (slice dir, -F), framework (path to .framework) }].
 */
export function flavoredFrameworks(ctx, { skipMissing = false } = {}) {
  const g = generatedPaths(ctx);
  if (!exists(g.rnFlavoredJson)) fail(`${g.rnFlavoredJson} missing; run the graph stage`);
  const doc = readJSON(g.rnFlavoredJson);
  const out = [];
  for (const f of doc.frameworks) {
    const slice = f.slices.find((s) => s.sdk === 'iphoneos*');
    if (!slice) fail(`flavored framework ${f.frameworkName} has no iphoneos slice`);
    const dir = path.join(g.xcframeworksPkg, ctx.flavor, f.artifactRelativePath, slice.libraryIdentifier);
    const framework = path.join(dir, slice.libraryPath);
    if (!exists(framework)) {
      if (skipMissing) continue;
      fail(`flavored framework missing: ${framework}`);
    }
    out.push({ id: f.id, name: f.frameworkName, executable: f.executableName, linkage: f.linkage, dir, framework });
  }
  return out;
}

export function jsiFrameworkDir(ctx) {
  return path.join(ctx.workRoot, 'jsi', ctx.flavor);
}

function swiftString(s) {
  return JSON.stringify(s);
}

/** App sources: the target's Swift files plus the plugin's generated ExpoModulesProvider.swift. */
function appSources(ctx, app) {
  const g = generatedPaths(ctx);
  const files = [];
  const native = [];
  for (const f of fs.readdirSync(app.sourceDir)) {
    if (f.endsWith('.swift')) files.push(path.join(app.sourceDir, f));
    else if (/\.(m|mm|c|cc|cpp)$/.test(f)) native.push(f);
  }
  if (native.length) {
    fail(
      `the app target has Objective-C/C++ sources (${native.join(', ')}). SwiftPM cannot mix them with the ` +
        `Swift app sources in one target; move them into a local Expo module (modules/) instead.`
    );
  }
  if (exists(g.generatedSourcesJson)) {
    for (const { path: p } of readJSON(g.generatedSourcesJson)) files.push(p);
  }
  return files;
}

function bridgingHeaderFlags(app) {
  if (!app.bridgingHeader || !exists(app.bridgingHeader)) return [];
  const text = fs.readFileSync(app.bridgingHeader, 'utf8');
  return /^\s*#\s*(import|include)/m.test(text) ? ['-import-objc-header', app.bridgingHeader] : [];
}

function macroPlugin(ctx) {
  const macros = resolvePackageDir(ctx.projectRoot, 'expo-modules-macros');
  return macros ? ['-Xfrontend', '-load-plugin-executable', '-Xfrontend', `${path.join(macros, 'apple/ExpoModulesMacros')}#ExpoModulesMacros`] : [];
}

/** Write the shell package. Sources are symlinked so edits need no regeneration. */
export function stageShell(ctx, app) {
  const g = generatedPaths(ctx);
  const dir = ctx.shellDir;
  const srcDir = path.join(dir, 'Sources', app.moduleName);
  // Drop links to sources that no longer exist (renamed files, other module name).
  rmrf(path.join(dir, 'Sources'));
  mkdirp(srcDir);
  for (const f of appSources(ctx, app)) fs.symlinkSync(f, path.join(srcDir, path.basename(f)));

  const debug = ctx.configuration === 'Debug';
  const swiftFlags = [
    '-D', debug ? 'EXPO_CONFIGURATION_DEBUG' : 'EXPO_CONFIGURATION_RELEASE',
    ...macroPlugin(ctx),
    ...bridgingHeaderFlags(app),
  ];
  const deps = [
    `.product(name: "ReactHeaders", package: "ReactNative")`,
    `.product(name: "ReactNativeHeaders", package: "ReactNative")`,
    `.product(name: "ReactNativeDependenciesHeaders", package: "ReactNative")`,
    `.product(name: "Autolinked", package: "Autolinked")`,
    `.product(name: "ReactCodegen", package: "React-GeneratedCode")`,
    `.product(name: "ReactAppDependencyProvider", package: "React-GeneratedCode")`,
  ];
  const packages = [
    `.package(name: "ReactNative", path: ${swiftString(g.xcframeworksPkg)})`,
    `.package(name: "React-GeneratedCode", path: ${swiftString(g.generatedIosPkg)})`,
    `.package(name: "Autolinked", path: ${swiftString(g.autolinkingPkg)})`,
  ];
  if (exists(path.join(g.jsiHeadersPkg, 'Package.swift'))) {
    packages.push(`.package(name: "ExpoModulesJSIHeaders", path: ${swiftString(g.jsiHeadersPkg)})`);
    deps.push(`.product(name: "ExpoModulesJSIHeaders", package: "ExpoModulesJSIHeaders")`);
  }
  const manifest = `// swift-tools-version: 6.0
// AUTO-GENERATED by expo-ios (stage shell) — the app target of ${path.basename(ctx.iosDir)}/${app.target}.xcodeproj.
import PackageDescription

let package = Package(
    name: "ExpoIosShell",
    platforms: [.iOS(${swiftString(app.minIOS)})],
    products: [
        .executable(name: ${swiftString(app.moduleName)}, targets: [${swiftString(app.moduleName)}]),
    ],
    dependencies: [
        ${packages.join(',\n        ')},
    ],
    targets: [
        .executableTarget(
            name: ${swiftString(app.moduleName)},
            dependencies: [
                ${deps.join(',\n                ')},
            ],
            path: ${swiftString(`Sources/${app.moduleName}`)},
            swiftSettings: [
                .define("DEBUG", .when(configuration: .debug)),
                .unsafeFlags([${swiftFlags.map(swiftString).join(', ')}]),
            ]
        ),
    ],
    swiftLanguageModes: [.v5],
    cxxLanguageStandard: .cxx20
)
`;
  writeIfChanged(path.join(dir, 'Package.swift'), manifest);
  info(`shell package ${dir}: ${fs.readdirSync(srcDir).join(', ')}`);
  return dir;
}

export function productsDir(ctx) {
  return path.join(ctx.scratchDir, 'out', 'Products', `${ctx.configuration}-iphoneos`);
}

/** `swift build` the shell (and through it the whole graph) for arm64 iOS. */
export function stageCompile(ctx, app) {
  const t = requireSdk(ctx);
  const frameworks = flavoredFrameworks(ctx);
  const fDirs = [...new Set(frameworks.map((f) => f.dir)), jsiFrameworkDir(ctx)];
  if (!exists(path.join(jsiFrameworkDir(ctx), 'ExpoModulesJSI.framework'))) fail('ExpoModulesJSI.framework missing; run the jsi stage');
  const linker = [
    '-ObjC',
    '-lc++',
    ...fDirs.flatMap((d) => ['-F', d]),
    ...frameworks.flatMap((f) => ['-framework', f.name]),
    '-rpath', '@executable_path/Frameworks',
    '-platform_version', 'ios', app.minIOS, ctx.sdkVersion,
    ...(ctx.configuration === 'Release' ? ['-dead_strip'] : []),
  ];
  const args = [
    'build',
    '--package-path', ctx.shellDir,
    '--scratch-path', ctx.scratchDir,
    '--configuration', ctx.configuration === 'Debug' ? 'debug' : 'release',
    ...swiftTargetArgs(ctx, app.minIOS),
    '--product', app.moduleName,
    '-j', String(Number(process.env.EXPO_IOS_JOBS) || navigatorConcurrency()),
    ...fDirs.flatMap((d) => ['-Xswiftc', `-F${d}`, '-Xcc', `-F${d}`]),
    ...linker.flatMap((a) => ['-Xlinker', a]),
  ];
  mkdirp(ctx.scratchDir);
  const log = path.join(ctx.logDir, `compile-${ctx.flavor}.log`);
  rmrf(log);
  run(t.swift, args, { cwd: ctx.shellDir, env: ctx.env, log });
  const exe = path.join(productsDir(ctx), app.moduleName);
  if (!exists(exe)) fail(`swift build finished but ${exe} is missing (see ${log})`);
  return exe;
}

function navigatorConcurrency() {
  try {
    return Math.max(1, (fs.readFileSync('/proc/cpuinfo', 'utf8').match(/^processor\s*:/gm) ?? [1]).length);
  } catch {
    return 4;
  }
}
