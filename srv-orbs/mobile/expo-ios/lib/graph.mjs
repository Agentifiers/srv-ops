// Stages `prebuild` and `graph`: Expo CNG → ios/, then React Native's SwiftPM graph
// with Expo's autolinking plugin.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fail, info, readJSON, run, sha256, warn, writeJSON, writeIfChanged, exists } from './util.mjs';
import { fixScaffoldedHeaderLayouts } from './fixups.mjs';

const PREBUILD_INPUTS = [
  'app.json',
  'app.config.js',
  'app.config.ts',
  'app.config.mjs',
  'app.config.cjs',
  'package.json',
  'package-lock.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lock',
  'bun.lockb',
];

function prebuildFingerprint(ctx) {
  const parts = [];
  for (const f of PREBUILD_INPUTS) {
    const p = path.join(ctx.projectRoot, f);
    if (exists(p)) parts.push(f, fs.readFileSync(p, 'utf8'));
  }
  return sha256(parts.join('\0'));
}

/**
 * `expo prebuild` asks for ios.bundleIdentifier when the config has none, and without a
 * TTY it can only proceed when its App Store lookup of the default finds nothing. Do what
 * its prompt would: write EXPO_IOS_BUNDLE_ID or com.anonymous.<slug> into the config with
 * Expo's own modifier (app.json; a dynamic config has to set it itself).
 */
function ensureBundleIdentifier(ctx) {
  const script = `
const path = require('path');
const root = process.argv[1];
const req = require('module').createRequire(path.join(root, 'package.json'));
const { getConfig } = req('@expo/config');
const exp = getConfig(root, { skipSDKVersionRequirement: true }).exp;
if (exp.ios && exp.ios.bundleIdentifier) { console.log(JSON.stringify({ existing: exp.ios.bundleIdentifier })); process.exit(0); }
const id = process.env.EXPO_IOS_BUNDLE_ID || ('com.anonymous.' + exp.slug).replace(/[^A-Za-z0-9.-]/g, '-');
const cli = path.dirname(req.resolve('@expo/cli/package.json'));
const { attemptModification } = require(path.join(cli, 'build/src/utils/modifyConfigAsync'));
attemptModification(root, { ios: { bundleIdentifier: id } }, { ios: { bundleIdentifier: id } })
  .then((ok) => console.log(JSON.stringify(ok ? { set: id } : { dynamic: id })));
`;
  const r = run(ctx.tools.node, ['-e', script, ctx.projectRoot], { cwd: ctx.projectRoot, env: ctx.env, capture: true });
  const res = JSON.parse(r.stdout.trim().split('\n').pop());
  if (res.dynamic) fail(`set expo.ios.bundleIdentifier in your app config (e.g. "${res.dynamic}"); expo-ios cannot edit a dynamic app.config`);
  if (res.set) info(`ios.bundleIdentifier was unset: wrote ${res.set} to the app config (set EXPO_IOS_BUNDLE_ID to choose another)`);
}

export function stagePrebuild(ctx, { clean = false } = {}) {
  ensureBundleIdentifier(ctx);
  const marker = path.join(ctx.stateDir, 'prebuild.json');
  const fingerprint = prebuildFingerprint(ctx);
  const hasIos = exists(ctx.iosDir) && fs.readdirSync(ctx.iosDir).some((f) => f.endsWith('.xcodeproj'));
  let args = null;
  if (!hasIos) args = [];
  else if (clean) args = ['--clean'];
  else if (!exists(marker)) {
    info('ios/ exists and was not generated by expo-ios: using it as is (pass --clean to regenerate)');
    return;
  } else if (readJSON(marker).fingerprint !== fingerprint) {
    info('app config, dependencies or lockfile changed: regenerating ios/');
    args = ['--clean'];
  }
  if (args == null) {
    info('ios/ is up to date');
    return;
  }
  const cli = path.join(ctx.expo, 'bin', 'cli');
  const env = ctx.env;
  run(ctx.tools.node, [cli, 'prebuild', '--platform', 'ios', '--no-install', ...args], {
    cwd: ctx.projectRoot,
    env,
    log: path.join(ctx.logDir, 'prebuild.log'),
  });
  // prebuild itself edits package.json (run scripts), so fingerprint what it left behind.
  writeJSON(marker, { fingerprint: prebuildFingerprint(ctx), generatedAt: new Date().toISOString() });
}

function setupSpm(ctx, action, extraEnv = {}) {
  const script = path.join(ctx.rn, 'scripts', 'setup-apple-spm.js');
  const args = [script, action, '--yes'];
  if (action === 'add') args.push('--deintegrate');
  const r = run(ctx.tools.node, args, {
    cwd: ctx.projectRoot,
    env: { ...ctx.env, ...extraEnv },
    log: path.join(ctx.logDir, 'graph.log'),
    allowFail: true,
  });
  // setup-apple-spm reports most failures through process.exitCode and logError.
  const failed = r.status !== 0 || /\[setup-apple-spm\][^\n]*(failed|error)/i.test(`${r.stdout}${r.stderr}`);
  return { status: failed ? r.status || 1 : 0, output: `${r.stdout}${r.stderr}` };
}

function injected(ctx) {
  const projects = fs.readdirSync(ctx.iosDir).filter((f) => f.endsWith('.xcodeproj'));
  return projects.some((p) => exists(path.join(ctx.iosDir, p, '.spm-injected.json')));
}

function errorBlock(output) {
  const lines = output.split('\n');
  const errs = lines.filter((l) => /^error:|error:|failed/i.test(l));
  return (errs.length ? errs : lines.slice(-40)).slice(0, 60).join('\n');
}

/**
 * Generate (or refresh) the SwiftPM graph. `pendingExclude` names modules whose
 * precompiled artifact the `modules` stage has yet to build; they stay out of this pass.
 */
export function stageGraph(ctx, { pendingExclude = [] } = {}) {
  const extraEnv = {
    EXPO_IOS_AUTOLINKING_EXCLUDE: [...ctx.exclude, ...pendingExclude].join(','),
  };
  let action = injected(ctx) ? 'update' : 'add';
  let r = setupSpm(ctx, action, extraEnv);
  if (r.status !== 0 && /Package\.swift is missing for library/.test(r.output)) {
    info('scaffolding Package.swift for libraries without SwiftPM support (pod ipc spec)');
    const s = setupSpm(ctx, 'scaffold', extraEnv);
    if (!/Self-managed|Scaffold/i.test(s.output) && s.status !== 0) fail(`setup-apple-spm scaffold failed:\n${errorBlock(s.output)}`);
    action = injected(ctx) ? 'update' : 'add';
    r = setupSpm(ctx, action, extraEnv);
  }
  if (r.status !== 0) fail(`setup-apple-spm ${action} failed (log: ${path.join(ctx.logDir, 'graph.log')}):\n${errorBlock(r.output)}`);
  if (/WARNING:|^warning:/m.test(r.output)) {
    for (const l of r.output.split('\n').filter((l) => /^warning:|WARNING:/.test(l))) warn(l.replace(/^warning:\s*/, ''));
  }
  fixScaffoldedHeaderDirs(ctx);
  fixScaffoldedCompilerFlags(ctx);
  fixScaffoldedPublicHeaders(ctx);
  injectPodDependencies(ctx);
  fixHeaderLayouts(ctx);
}

/**
 * The scaffolder leaves out compiler flags a podspec sets through pod_target_xcconfig
 * (RNScreens: OTHER_CPLUSPLUSFLAGS -DRNS_GAMMA_ENABLED=1, without which its gamma sources
 * do not compile). Read them with `pod ipc spec` and add them as unsafeFlags.
 */
function fixScaffoldedCompilerFlags(ctx) {
  const libs = path.join(generatedPaths(ctx).autolinkingPkg, 'libs');
  if (!exists(libs)) return;
  const MARK = '/* expo-ios: podspec xcconfig flags */';
  for (const lib of fs.readdirSync(libs)) {
    const dir = fs.realpathSync(path.join(libs, lib));
    const manifest = path.join(dir, 'Package.swift');
    if (!exists(manifest)) continue;
    let text = fs.readFileSync(manifest, 'utf8');
    if (!text.includes('AUTO-SCAFFOLDED') || text.includes(MARK)) continue;
    const podspec = fs.readdirSync(dir).find((f) => f.endsWith('.podspec'));
    if (!podspec) continue;
    // React Native's reader: strips install_modules_dependencies & co. before `pod ipc spec`.
    const reader = path.join(ctx.rn, 'scripts/spm/read-podspec.js');
    const r = run(ctx.tools.node, ['-e', 'console.log(JSON.stringify(require(process.argv[1]).runPodIpcSpec(process.argv[2])))', reader, path.join(dir, podspec)], {
      cwd: dir,
      env: ctx.env,
      capture: true,
    });
    const spec = JSON.parse(r.stdout.trim().split('\n').pop());
    if (!spec) fail(`pod ipc spec could not read ${path.join(dir, podspec)}`);
    const c = [];
    const cxx = [];
    const split = (v) => (Array.isArray(v) ? v : String(v ?? '').split(/\s+/)).filter((f) => f && !f.includes('$('));
    for (const s of [spec, ...(spec.subspecs ?? [])]) {
      const x = s.pod_target_xcconfig ?? {};
      for (const d of split(x.GCC_PREPROCESSOR_DEFINITIONS)) c.push(`-D${d}`), cxx.push(`-D${d}`);
      for (const f of split(x.OTHER_CFLAGS)) c.push(f), cxx.push(f);
      for (const f of split(x.OTHER_CPLUSPLUSFLAGS)) cxx.push(f);
    }
    const fmt = (flags) => `.unsafeFlags(${JSON.stringify([...new Set(flags)])}) ${MARK}, `;
    if (c.length) text = text.replace(/cSettings: \[/g, `cSettings: [${fmt(c)}`);
    if (cxx.length) text = text.replace(/cxxSettings: \[/g, `cxxSettings: [${fmt(cxx)}`);
    if (!c.length && !cxx.length) text = text.replace(/\n/, `\n// ${MARK} none\n`);
    fs.writeFileSync(manifest, text);
    if (c.length || cxx.length) info(`${lib}: podspec flags ${[...new Set(cxx)].join(' ')}`);
  }
}

/**
 * CocoaPods' `header_dir = "X"` publishes a subspec's headers as <X/Header.h> (RNScreens'
 * "common" subspec: #include <rnscreens/RNSTabsHostComponentDescriptor.h>). React
 * Native's scaffolder drops that, so stage the headers under .expo-ios-headers/X/ and put
 * the staging dir on the scaffolded target's header search path.
 */
function fixScaffoldedHeaderDirs(ctx) {
  const libs = path.join(generatedPaths(ctx).autolinkingPkg, 'libs');
  if (!exists(libs)) return;
  for (const lib of fs.readdirSync(libs)) {
    const dir = fs.realpathSync(path.join(libs, lib));
    const manifest = path.join(dir, 'Package.swift');
    if (!exists(manifest)) continue;
    let text = fs.readFileSync(manifest, 'utf8');
    if (!text.includes('AUTO-SCAFFOLDED')) continue;
    const podspec = fs.readdirSync(dir).find((f) => f.endsWith('.podspec'));
    if (!podspec) continue;
    const spec = fs.readFileSync(path.join(dir, podspec), 'utf8');
    let staged = false;
    for (const block of spec.split(/\.subspec\s/).slice(1)) {
      const hd = /\.header_dir\s*=\s*["']([^"']+)["']/.exec(block);
      const sf = /\.source_files\s*=\s*\[?([^\n]+)/.exec(block);
      if (!hd || !sf) continue;
      const globs = [...sf[1].matchAll(/["']([^"']+)["']/g)].map((m) => m[1]);
      const stage = path.join(dir, '.expo-ios-headers', hd[1]);
      fs.mkdirSync(stage, { recursive: true });
      for (const glob of globs) {
        const base = glob.split('/**')[0].split('/*')[0];
        if (!exists(path.join(dir, base))) continue;
        for (const rel of walkFiles(path.join(dir, base))) {
          if (!rel.endsWith('.h')) continue;
          const link = path.join(stage, path.basename(rel));
          if (!exists(link)) fs.symlinkSync(path.join(dir, base, rel), link);
        }
      }
      staged = true;
    }
    if (staged && !text.includes('.headerSearchPath(".expo-ios-headers")')) {
      text = text.replace(/(cSettings|cxxSettings): \[/g, '$1: [.headerSearchPath(".expo-ios-headers"), ');
      fs.writeFileSync(manifest, text);
      info(`${lib}: staged header_dir headers in ${path.join(dir, '.expo-ios-headers')}`);
    }
  }
}

const PUBLIC_DIR = '.expo-ios-public';
const PUBLIC_MARK = '// expo-ios: CocoaPods-style public headers';

/**
 * SwiftPM makes a scaffolded target's Clang module from `publicHeadersPath` as an umbrella
 * *directory* and gives dependents only `-I <publicHeadersPath>`. CocoaPods instead
 * publishes the spec's source_files headers (minus exclude_files) flattened into
 * Headers/Public/<Pod>/. Two things break when the layouts differ:
 *  - headers the podspec excludes still land in the module (RNScreens with
 *    RNS_GAMMA_ENABLED=1: ios/stubs/RNSGammaStubs.h re-declares the gamma classes →
 *    "duplicate interface definition for class 'RNSStackHostComponentView'");
 *  - public headers that `#import "Sibling.h"` from another subdirectory only resolve
 *    through the target's private search paths, so every dependent building the module
 *    fails ("'RNSDefines.h' file not found" from RNSConvert.h).
 * For such targets publish what CocoaPods would: a flat dir of symlinks to the headers the
 * scaffolded `sources` list keeps, the podspec header_dir trees staged by
 * fixScaffoldedHeaderDirs next to them (outside the module), and a module map.
 */
function fixScaffoldedPublicHeaders(ctx) {
  const libs = path.join(generatedPaths(ctx).autolinkingPkg, 'libs');
  if (!exists(libs)) return;
  for (const lib of fs.readdirSync(libs)) {
    const dir = fs.realpathSync(path.join(libs, lib));
    const manifest = path.join(dir, 'Package.swift');
    if (!exists(manifest)) continue;
    let text = fs.readFileSync(manifest, 'utf8');
    if (!text.includes('AUTO-SCAFFOLDED')) continue;
    for (const block of text.split(/\.target\(/).slice(1)) {
      const name = /^\s*name:\s*"([^"]+)"/.exec(block)?.[1];
      const pubDecl = /publicHeadersPath:\s*"([^"]+)"(?: \/\* expo-ios: was "([^"]+)" \*\/)?/.exec(block);
      const srcBlock = /\bsources:\s*\[([\s\S]*?)\]/.exec(block)?.[1];
      if (!name || !pubDecl || srcBlock === undefined) continue;
      const pub = pubDecl[2] ?? pubDecl[1];
      const root = path.resolve(dir, /\bpath:\s*"([^"]+)"/.exec(block)?.[1] ?? `Sources/${name}`);
      const pubDir = path.join(root, pub);
      if (!exists(pubDir)) continue;
      // An umbrella header makes SwiftPM use it instead of the directory.
      if (exists(path.join(pubDir, `${name}.h`)) || exists(path.join(pubDir, name, `${name}.h`))) continue;
      if (exists(path.join(pubDir, 'module.modulemap'))) continue;
      const sources = new Set([...srcBlock.matchAll(/"([^"]+)"/g)].map((m) => path.normalize(m[1]).replace(/\/$/, '')));
      // A `sources` entry may be a file or a directory (everything below it is in).
      const listed = (rel) => {
        for (let p = path.normalize(path.join(pub, rel)); p !== '.' && p !== '/'; p = path.dirname(p)) if (sources.has(p)) return true;
        return false;
      };
      const headers = walkFiles(pubDir).filter((rel) => /\.(h|hh|hpp)$/.test(rel) && !rel.startsWith('.expo-ios-'));
      const kept = headers.filter(listed).sort();
      const excluded = headers.filter((rel) => !listed(rel));
      const byName = new Map();
      for (const rel of kept) if (!byName.has(path.basename(rel))) byName.set(path.basename(rel), rel);
      // Quote includes that only resolve through the target's private search paths.
      const crossDir = kept.some((rel) =>
        [...fs.readFileSync(path.join(pubDir, rel), 'utf8').matchAll(/^\s*#\s*(?:import|include)\s+"([^"]+)"/gm)].some(
          ([, inc]) => !exists(path.join(pubDir, path.dirname(rel), inc)) && byName.has(path.basename(inc))
        )
      );
      if (!excluded.length && !crossDir) continue;

      const flat = path.join(dir, PUBLIC_DIR);
      fs.rmSync(flat, { recursive: true, force: true });
      fs.mkdirSync(flat, { recursive: true });
      for (const [base, rel] of byName) fs.symlinkSync(path.join(pubDir, rel), path.join(flat, base));
      const dupes = kept.length - byName.size;
      // <hd/X.h> includes (header_dir) resolve through the dependents' -I <public dir>.
      const staged = path.join(dir, '.expo-ios-headers');
      const hidden = [];
      if (exists(staged)) {
        for (const hd of fs.readdirSync(staged)) {
          if (byName.has(hd)) continue;
          fs.symlinkSync(path.join(staged, hd), path.join(flat, hd));
          for (const rel of walkFiles(path.join(staged, hd))) hidden.push(`${hd}/${rel}`);
        }
      }
      fs.writeFileSync(
        path.join(flat, 'module.modulemap'),
        `${PUBLIC_MARK} of ${name}\nmodule ${name} {\n  umbrella "."\n${hidden.map((h) => `  exclude header ${JSON.stringify(h)}\n`).join('')}  export *\n}\n`
      );
      if (!pubDecl[2]) {
        text = text.replace(pubDecl[0], `publicHeadersPath: "${path.relative(root, flat)}" /* expo-ios: was "${pub}" */`);
        // The original directory stays on the target's own search path.
        if (!text.includes(`.headerSearchPath("${pub}")`)) text = text.replace(/(cSettings|cxxSettings): \[/g, `$1: [.headerSearchPath("${pub}"), `);
        fs.writeFileSync(manifest, text);
      }
      info(
        `${lib}: CocoaPods-style public headers in ${PUBLIC_DIR} (${byName.size} kept, ${excluded.length} excluded by the podspec` +
          `${excluded.length ? `: ${excluded.slice(0, 3).join(', ')}${excluded.length > 3 ? ', …' : ''}` : ''}${dupes ? `, ${dupes} duplicate basenames skipped` : ''})`
      );
    }
  }
}

function walkFiles(root) {
  const out = [];
  const visit = (rel) => {
    for (const e of fs.readdirSync(path.join(root, rel), { withFileTypes: true })) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) visit(r);
      else out.push(r);
    }
  };
  visit('');
  return out;
}


/**
 * Expo's plugin generates source packages that only depend on React's header products.
 * A module whose podspec depends on an autolinked React Native library (expo-router →
 * RNScreens: `add_dependency(s, "RNScreens")`) then fails with "unable to resolve module
 * dependency". Add the library's package and product, as CocoaPods would.
 */
function injectPodDependencies(ctx) {
  const g = generatedPaths(ctx);
  const sources = path.join(g.expoDir, 'expo-source');
  const libs = path.join(g.autolinkingPkg, 'libs');
  if (!exists(sources) || !exists(libs)) return;
  for (const name of fs.readdirSync(sources)) {
    const manifest = path.join(sources, name, 'Package.swift');
    const root = path.join(sources, name, 'root');
    if (!exists(manifest) || !exists(root)) continue;
    const podspecs = [];
    for (const dir of [root, path.join(root, 'ios'), path.join(root, 'apple')]) {
      if (exists(dir)) for (const f of fs.readdirSync(dir)) if (f.endsWith('.podspec')) podspecs.push(path.join(dir, f));
    }
    const deps = new Set();
    for (const p of podspecs) {
      const text = fs.readFileSync(p, 'utf8').replace(/^\s*\w+\.test_spec[\s\S]*?^\s*end\b/gm, '');
      for (const m of text.matchAll(/(?:\bs\.dependency\s*|add_dependency\(\s*\w+\s*,\s*)['"]([A-Za-z0-9_-]+)['"]/g)) deps.add(m[1]);
    }
    let text = fs.readFileSync(manifest, 'utf8');
    let changed = false;
    for (const dep of deps) {
      const libManifest = path.join(libs, dep, 'Package.swift');
      if (!exists(libManifest) || text.includes(`package: "${dep}")`)) continue;
      const libText = fs.readFileSync(libManifest, 'utf8');
      if (!new RegExp(`\\.library\\(name: "${dep}"`).test(libText)) continue;
      // The library's headers select declarations by the podspec defines it compiles with
      // (RNS_GAMMA_ENABLED); a consumer building its Clang module needs them too. Its
      // headers resolve through the CocoaPods-style public dir (fixScaffoldedPublicHeaders).
      const defines = [...new Set([...libText.matchAll(/"(-D[A-Za-z0-9_]+(?:=[^"]*)?)"/g)].map((m) => m[1]))];
      text = text
        .replace(/(\n    dependencies: \[\n)/, `$1        .package(name: "${dep}", path: ${JSON.stringify(path.join(libs, dep))}),\n`)
        .replace(/(\.target\(\n\s*name: "[^"]+",\n\s*dependencies: \[\n)/g, `$1                .product(name: "${dep}", package: "${dep}"),\n`);
      if (defines.length) {
        const swiftDefs = defines.flatMap((f) => ['-Xcc', f]).map((f) => JSON.stringify(f)).join(', ');
        const cDefs = defines.map((f) => JSON.stringify(f)).join(', ');
        text = text
          .replace(/swiftSettings: \[\.unsafeFlags\(\[/g, `swiftSettings: [.unsafeFlags([${swiftDefs}, `)
          .replace(/(cSettings|cxxSettings): \[\.unsafeFlags\(\[/g, `$1: [.unsafeFlags([${cDefs}, `);
      }
      changed = true;
      info(`${name}: added podspec dependency ${dep} (libs/${dep})`);
    }
    if (changed) fs.writeFileSync(manifest, text);
  }
}

/** Gap 5: load the whole graph once and give scaffolded umbrella layouts a module map. */
function fixHeaderLayouts(ctx) {
  const autolinked = path.join(ctx.iosDir, 'build/generated/autolinking');
  for (let attempt = 0; attempt < 4; attempt++) {
    const r = run(ctx.tools.swift ?? 'swift', ['package', '--package-path', autolinked, 'show-dependencies', '--format', 'json'], {
      env: ctx.env,
      capture: true,
      allowFail: true,
    });
    if (r.status === 0) return;
    const errors = [...`${r.stdout}${r.stderr}`.matchAll(/target '([^']+)' has invalid header layout: umbrella header found at '([^']+)'/g)];
    if (errors.length === 0) fail(`the SwiftPM graph does not load:\n${r.stderr.split('\n').slice(0, 40).join('\n')}`);
    fixScaffoldedHeaderLayouts(errors.map(([, target, umbrella]) => ({ target, umbrella })));
  }
  fail('the SwiftPM graph still has invalid header layouts after adding module maps');
}

/** `expo-modules-autolinking resolve` with the configuration's exclusions. */
export function resolveExpoModules(ctx, extraExclude = []) {
  const bin = path.join(path.dirname(require_resolve(ctx, 'expo-modules-autolinking/package.json')), 'bin', 'expo-modules-autolinking.js');
  const r = run(ctx.tools.node, [bin, 'resolve', '--platform', 'apple', '--json'], {
    cwd: ctx.projectRoot,
    env: { ...ctx.env, EXPO_IOS_AUTOLINKING_EXCLUDE: [...ctx.exclude, ...extraExclude].join(',') },
    capture: true,
  });
  const parsed = JSON.parse(r.stdout);
  return Array.isArray(parsed) ? parsed : parsed.modules ?? [];
}


function require_resolve(ctx, spec) {
  return createRequire(path.join(ctx.expo, 'package.json')).resolve(spec);
}

export function generatedPaths(ctx) {
  const build = path.join(ctx.iosDir, 'build');
  return {
    xcframeworksPkg: path.join(build, 'xcframeworks'),
    generatedIosPkg: path.join(build, 'generated/ios'),
    autolinkingPkg: path.join(build, 'generated/autolinking'),
    expoDir: path.join(build, 'generated/autolinking/expo'),
    compileInterfaces: path.join(build, 'generated/autolinking/expo/compile-interfaces'),
    jsiHeadersPkg: path.join(build, 'generated/autolinking/expo/ExpoModulesJSIHeaders'),
    flavoredFrameworksJson: path.join(build, 'generated/autolinking/.spm-plugin-flavored-frameworks.json'),
    generatedSourcesJson: path.join(build, 'generated/autolinking/.spm-plugin-generated-sources.json'),
    scriptPhasesJson: path.join(build, 'generated/autolinking/.spm-plugin-script-phases.json'),
    rnFlavoredJson: path.join(build, 'xcframeworks/flavored-frameworks.json'),
  };
}
